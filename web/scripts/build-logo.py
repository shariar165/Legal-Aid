"""Build the যুক্তি · Jukti mark (spec 22): the matra of যু is the beam of a balance.

One-off: needs fonttools + uharfbuzz and Noto Serif Bengali (OFL). Writes
  src/app/icon.svg, src/components/brand/logo-paths.ts, and logo-*.svg previews into OUT_DIR.
Usage: python scripts/build-logo.py FONT.ttf OUT_DIR
The PNG/ICO rasters are made by scripts/raster-logo.mjs (sharp) from icon.svg and icon-simple.svg.
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from shape_glyphs import shape  # noqa: E402

TILE, CREAM, GOLD = "#0f4c3a", "#fffdf8", "#f5c443"
WEB = Path(__file__).resolve().parent.parent

# glyph units of যু in Noto Serif Bengali Bold: matra top -622, matra bottom -550
MATRA_TOP, MATRA_BOT = -622, -550
S = 0.30           # glyph scale into the 512 box
BEAM_Y = 150       # where the matra top lands in the box


def mark(glyph: dict, simple: bool = False) -> str:
    x0, _, x1, _ = glyph["bbox"]
    gx = 256 - (x0 + x1) / 2 * S                  # centre the glyph
    gy = BEAM_Y - MATRA_TOP * S
    beam_h = (MATRA_BOT - MATRA_TOP) * S
    bx0, bx1 = 70, 442                            # beam ends
    pan_w, drop = 74, 96
    parts = [f'<rect width="512" height="512" rx="112" fill="{TILE}"/>']
    if simple:
        # no glyph at favicon size: a post under the beam's centre and a foot
        parts.append(f'<rect x="240" y="{BEAM_Y}" width="32" height="250" fill="{CREAM}"/>')
        parts.append(f'<rect x="176" y="{BEAM_Y + 236}" width="160" height="30" rx="15" fill="{CREAM}"/>')
    else:
        parts.append(f'<path transform="translate({gx:.1f} {gy:.1f}) scale({S})" fill="{CREAM}" d="{glyph["d"]}"/>')
    # the beam (over the matra) and a pivot on top of it
    parts.append(f'<rect x="{bx0}" y="{BEAM_Y:.1f}" width="{bx1 - bx0}" height="{beam_h:.1f}" rx="{beam_h / 2:.1f}" fill="{GOLD}"/>')
    parts.append(f'<circle cx="256" cy="{BEAM_Y - 14:.1f}" r="16" fill="{GOLD}"/>')
    for cx in (bx0 + 18, bx1 - 18):
        top = BEAM_Y + beam_h
        py = top + drop
        parts.append(
            f'<path d="M{cx} {top:.1f}L{cx - pan_w / 2 + 6} {py:.1f}M{cx} {top:.1f}L{cx + pan_w / 2 - 6} {py:.1f}" '
            f'stroke="{GOLD}" stroke-width="7" stroke-linecap="round" fill="none"/>'
        )
        parts.append(f'<path d="M{cx - pan_w / 2} {py:.1f}H{cx + pan_w / 2}A{pan_w / 2} {pan_w / 2 * 0.62} 0 0 1 {cx - pan_w / 2} {py:.1f}Z" fill="{GOLD}"/>')
    return "\n  ".join(parts)


def svg(body: str) -> str:
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">\n  {body}\n</svg>\n'


if __name__ == "__main__":
    glyph = shape(sys.argv[1], "যু")
    out = Path(sys.argv[2])
    out.mkdir(parents=True, exist_ok=True)
    full, simple = svg(mark(glyph)), svg(mark(glyph, simple=True))
    (out / "icon.svg").write_text(full, encoding="utf-8")
    (out / "icon-simple.svg").write_text(simple, encoding="utf-8")
    (WEB / "src/app/icon.svg").write_text(full, encoding="utf-8")
    ts = WEB / "src/components/brand/logo-paths.ts"
    ts.parent.mkdir(parents=True, exist_ok=True)
    ts.write_text(
        "// Generated by scripts/build-logo.py (spec 22). Do not edit by hand: re-run the script.\n"
        "// The যুক্তি mark: the matra of যু (Noto Serif Bengali Bold, OFL, outlined) is the beam of a balance.\n"
        f"export const LOGO_SVG_BODY = {json.dumps(mark(glyph), ensure_ascii=False)};\n",
        encoding="utf-8",
    )
    print(json.dumps({"ok": True, "out": str(out)}))
