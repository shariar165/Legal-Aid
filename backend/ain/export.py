"""DOCX export of the memorandum, with the verification ledger as an appendix."""

from __future__ import annotations

import io

from docx import Document as Docx
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Pt, RGBColor

from ain.models import AnalysisResult
from ain.naming import label

MARK = {"verified": "✔ verified", "partial": "⚠ partial", "dropped": "✘ dropped"}


def memo_docx(r: AnalysisResult) -> bytes:
    d = Docx()
    style = d.styles["Normal"]
    style.font.name = "Calibri"
    style.font.size = Pt(10.5)

    d.add_heading(r.memo.title, level=0)
    p = d.add_paragraph()
    p.add_run(f"Prepared for: {r.memo.prepared_for}\n").bold = True
    p.add_run("Ain Copilot · multi-agent analysis with verified citations · decision support, not legal advice")
    d.add_heading("Executive summary", level=1)
    d.add_paragraph(r.memo.executive_summary)
    d.add_paragraph(r.memo.summary_bn)
    d.add_heading("Applicable law", level=1)
    d.add_paragraph(r.memo.jurisdiction_note)

    sections = {v.claim.citation_id: v.section for v in r.ledger if v.section}
    risks = {k.id: k for k in r.risks}
    for n, issue in enumerate(r.memo.issues, 1):
        risk = risks.get(issue.risk_id)
        d.add_heading(f"{n}. {issue.heading}", level=1)
        if risk:
            meta = d.add_paragraph()
            meta.add_run(f"Severity: {risk.severity.upper()}   Origin: {risk.origin}").italic = True
            if risk.clash:
                meta.add_run(f"\nValid abroad, void in BD: {risk.clash}").italic = True
            if risk.bench:
                meta.add_run(f"\nVirtual Bench {risk.bench.vote}: {risk.bench.majority_opinion}").italic = True
                if risk.bench.dissent:
                    meta.add_run(f"\nDissent: {risk.bench.dissent} (flagged for human review)").italic = True
        for title, body in (("Issue", issue.issue), ("Rule", issue.rule), ("Application", issue.application), ("Conclusion", issue.conclusion)):
            para = d.add_paragraph()
            para.add_run(f"{title}. ").bold = True
            para.add_run(body)
        cites = [label(sections[c]).en for c in issue.citation_ids if c in sections]
        if cites:
            d.add_paragraph("Authorities: " + "; ".join(cites))
        if issue.mitigation_clause:
            q = d.add_paragraph()
            q.add_run("Suggested replacement clause: ").bold = True
            q.add_run(issue.mitigation_clause).italic = True

    if r.wage:
        w = r.wage
        d.add_heading("Wage calculation", level=1)
        d.add_paragraph(
            f"Promised {w.currency} {w.promised:,.0f}; deductions {w.currency} {w.monthly_deductions:,.0f} per month ({w.pct_deducted}%); "
            f"take-home {w.currency} {w.net:,.0f}."
            + (f" Legal minimum {w.currency} {w.minimum_wage:,.0f}." if w.minimum_wage else "")
            + (" Salary confirmed by the user." if w.confirmed_by_user else "")
        )

    d.add_heading("Caveats", level=1)
    for c in r.memo.caveats:
        d.add_paragraph(c, style="List Bullet")

    d.add_page_break()
    d.add_heading("Appendix - Verification Ledger", level=1)
    t = d.add_table(rows=1, cols=5)
    t.style = "Light Grid Accent 1"
    for cell, h in zip(t.rows[0].cells, ("Claim", "Citation", "Gates (E/F/J/C)", "Result", "Source")):
        cell.text = h
    for v in r.ledger:
        row = t.add_row().cells
        row[0].text = v.claim.proposition[:300]
        row[1].text = label(v.section).en if v.section else v.claim.citation_id
        row[2].text = " / ".join(g.status for g in v.gates)
        row[3].text = MARK[v.verdict] + (f"\n{v.note}" if v.note else "")
        row[4].text = v.section.url if v.section else "-"
        if v.verdict == "dropped":
            for par in row[3].paragraphs:
                for run in par.runs:
                    run.font.color.rgb = RGBColor(0xB4, 0x23, 0x18)
    foot = d.add_paragraph(f"Generated by Ain Copilot · mode {r.llm_mode} · {r.stats.verified} verified / {r.stats.partial} partial / {r.stats.dropped} dropped claims")
    foot.alignment = WD_ALIGN_PARAGRAPH.CENTER
    buf = io.BytesIO()
    d.save(buf)
    return buf.getvalue()
